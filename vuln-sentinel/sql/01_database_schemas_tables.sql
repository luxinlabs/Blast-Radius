create or replace database VULN_SENTINEL_DB COMMENT='Blast-Radius: npm/PyPI packages, OSV advisories, threat intel';

create or replace schema VULN_SENTINEL_DB.CORE;

create or replace TABLE VULN_SENTINEL_DB.CORE.ADVISORIES (
	ADVISORY_ID VARCHAR(16777216) NOT NULL,
	ECOSYSTEM VARCHAR(16777216),
	ALIASES ARRAY,
	CVE_IDS ARRAY,
	SUMMARY VARCHAR(16777216),
	DETAILS VARCHAR(16777216),
	SEVERITY VARCHAR(16777216),
	CVSS_VECTOR VARCHAR(16777216),
	PUBLISHED TIMESTAMP_TZ(9),
	MODIFIED TIMESTAMP_TZ(9),
	WITHDRAWN TIMESTAMP_TZ(9),
	REFERENCES ARRAY,
	primary key (ADVISORY_ID)
);

create or replace TABLE VULN_SENTINEL_DB.CORE.AFFECTED_RANGES (
	ADVISORY_ID VARCHAR(16777216),
	ECOSYSTEM VARCHAR(16777216),
	PACKAGE_NAME VARCHAR(16777216),
	RANGE_TYPE VARCHAR(16777216),
	INTRODUCED VARCHAR(16777216),
	FIXED VARCHAR(16777216),
	LAST_AFFECTED VARCHAR(16777216),
	AFFECTED_VERSIONS ARRAY
);

create or replace TABLE VULN_SENTINEL_DB.CORE.DEPENDENCIES (
	ECOSYSTEM VARCHAR(16777216),
	PARENT VARCHAR(16777216),
	PARENT_VERSION VARCHAR(16777216),
	CHILD VARCHAR(16777216),
	VERSION_SPEC VARCHAR(16777216),
	DEP_KIND VARCHAR(16777216),
	DEPTH NUMBER(38,0),
	LOADED_AT TIMESTAMP_NTZ(9)
);

create or replace TABLE VULN_SENTINEL_DB.CORE.PACKAGES (
	ECOSYSTEM VARCHAR(16777216) NOT NULL,
	NAME VARCHAR(16777216) NOT NULL,
	LATEST_VERSION VARCHAR(16777216),
	DESCRIPTION VARCHAR(16777216),
	LICENSE VARCHAR(16777216),
	REPOSITORY VARCHAR(16777216),
	HOMEPAGE VARCHAR(16777216),
	MAINTAINERS ARRAY,
	MONTHLY_DOWNLOADS NUMBER(38,0),
	VERSION_COUNT NUMBER(38,0),
	LAST_PUBLISHED TIMESTAMP_TZ(9),
	UPDATED_AT TIMESTAMP_TZ(9),
	primary key (ECOSYSTEM, NAME)
);

create or replace TABLE VULN_SENTINEL_DB.CORE.PACKAGE_VERSIONS (
	ECOSYSTEM VARCHAR(16777216) NOT NULL,
	NAME VARCHAR(16777216) NOT NULL,
	VERSION VARCHAR(16777216) NOT NULL,
	PUBLISHED_AT TIMESTAMP_TZ(9),
	YANKED BOOLEAN,
	DEPRECATED VARCHAR(16777216),
	primary key (ECOSYSTEM, NAME, VERSION)
);

create or replace TABLE VULN_SENTINEL_DB.CORE.WATCHLIST (
	ECOSYSTEM VARCHAR(16777216),
	NAME VARCHAR(16777216),
	RUNS_WHERE VARCHAR(16777216),
	IS_MOSTLY_TRANSITIVE BOOLEAN,
	HANDLES_SECRETS BOOLEAN,
	SECRET_TYPES ARRAY,
	DEMO_REASON VARCHAR(16777216),
	ADDED_AT TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP()
);

create or replace schema VULN_SENTINEL_DB.INTEL;

create or replace schema VULN_SENTINEL_DB.PUBLIC;

create or replace schema VULN_SENTINEL_DB.RAW;

create or replace TABLE VULN_SENTINEL_DB.RAW.OSV_RECORDS (
	ID VARCHAR(16777216),
	ECOSYSTEM VARCHAR(16777216),
	MODIFIED TIMESTAMP_TZ(9),
	RECORD VARIANT,
	LOADED_AT TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP()
);

create or replace TABLE VULN_SENTINEL_DB.RAW.REGISTRY_RECORDS (
	ECOSYSTEM VARCHAR(16777216),
	NAME VARCHAR(16777216),
	RECORD VARIANT,
	DOWNLOADS NUMBER(38,0),
	LOADED_AT TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP()
);

create or replace schema VULN_SENTINEL_DB.SERVING;

create or replace TABLE VULN_SENTINEL_DB.SERVING.PACKAGE_VERSION_RISK (
	ECOSYSTEM VARCHAR(16777216),
	NAME VARCHAR(16777216),
	VERSION VARCHAR(16777216),
	PUBLISHED_AT TIMESTAMP_TZ(9),
	YANKED BOOLEAN,
	DEPRECATED VARCHAR(16777216),
	IN_REGISTRY BOOLEAN,
	ADVISORY_ID VARCHAR(16777216),
	INCIDENT_TYPE VARCHAR(17),
	SEVERITY VARCHAR(16777216),
	CVSS_VECTOR VARCHAR(16777216),
	SUMMARY VARCHAR(16777216),
	CVE_IDS ARRAY,
	FIXED VARCHAR(16777216)
);

create or replace TABLE VULN_SENTINEL_DB.SERVING.RESPONSE_PLAYBOOK (
	INCIDENT_TYPE VARCHAR(16777216),
	STEP_NO NUMBER(38,0),
	PHASE VARCHAR(16777216),
	ACTION VARCHAR(16777216),
	APPLIES_WHEN VARCHAR(16777216),
	OWNER VARCHAR(16777216),
	AUTOMATABLE BOOLEAN
);
