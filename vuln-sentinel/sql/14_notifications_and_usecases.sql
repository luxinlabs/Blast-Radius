-- Additive: notification center, client use-case maps and injected threat events. Run after 10 and 13.
CREATE TABLE IF NOT EXISTS VULN_SENTINEL_DB.SERVING.THREAT_EVENTS (
  event_id VARCHAR PRIMARY KEY,
  ecosystem VARCHAR NOT NULL,
  name VARCHAR NOT NULL,
  payload VARCHAR NOT NULL,
  created_at VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS VULN_SENTINEL_DB.SERVING.NOTIFICATIONS (
  notification_id VARCHAR PRIMARY KEY,
  client_id VARCHAR NOT NULL,
  kind VARCHAR NOT NULL,
  priority VARCHAR NOT NULL,
  status VARCHAR NOT NULL,
  payload VARCHAR NOT NULL,
  response VARCHAR,
  created_at VARCHAR NOT NULL,
  updated_at VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS VULN_SENTINEL_DB.SERVING.USE_CASES (
  client_id VARCHAR PRIMARY KEY,
  payload VARCHAR NOT NULL,
  created_at VARCHAR NOT NULL
);

-- The app role updates notifications and replaces a client's use-case map; audit events stay append-only.
GRANT SELECT,INSERT,UPDATE ON TABLE VULN_SENTINEL_DB.SERVING.NOTIFICATIONS TO ROLE VULN_SENTINEL_APP;
GRANT SELECT,INSERT,DELETE ON TABLE VULN_SENTINEL_DB.SERVING.USE_CASES TO ROLE VULN_SENTINEL_APP;
GRANT SELECT,INSERT ON TABLE VULN_SENTINEL_DB.SERVING.THREAT_EVENTS TO ROLE VULN_SENTINEL_APP;
